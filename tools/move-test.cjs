const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const http = require('http'), fs = require('fs'), path = require('path'), { spawn } = require('child_process');
const root = path.join(__dirname, '..', 'dist', 'client');
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' };
const web = http.createServer((q, s) => { const f = path.join(root, q.url.split('?')[0] === '/' ? 'index.html' : q.url.split('?')[0]); fs.readFile(f, (e, d) => { s.writeHead(e ? 404 : 200, { 'Content-Type': types[path.extname(f)] || 'x' }); s.end(d); }); }).listen(8098);
const srv = spawn('node', [path.join(__dirname, '..', 'dist', 'server.cjs'), '7798'], { stdio: 'ignore' });
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  await sleep(700);
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 800, height: 500 } });
  page.on('pageerror', e => console.log('PAGEERROR', e.message));
  await page.goto('http://127.0.0.1:8098/?join=127.0.0.1:7798&token=dedicated&name=Host');
  await sleep(2500);
  const pos = () => page.evaluate(() => { const g = window.__game; const me = g.st.players.find(p => p.id === g.myId); return { phase: g.st.phase, x: g.body.x.toFixed(2), z: g.body.z.toFixed(2), fps: g.fpsN, you: { frozen: g.st.you.frozen, speed: g.st.you.speedMul }, pending: g.pending.length }; });
  console.log('lobby', await pos());
  await page.evaluate(() => { window.__game.keys.add('KeyW'); });
  await sleep(1500);
  console.log('lobby after W', await pos());
  await page.evaluate(() => { const g = window.__game; g.keys.clear(); g.net.send({ t: 'debug', cmd: 'spawn_bots', a: { n: 5 } }); g.net.send({ t: 'debug', cmd: 'bot_mode', a: { mode: 'idle' } }); });
  await sleep(500);
  await page.evaluate(() => window.__game.net.send({ t: 'start' }));
  await sleep(12500);
  console.log('work', await pos());
  await page.evaluate(() => { window.__game.keys.add('KeyW'); });
  await sleep(1500);
  console.log('work after W', await pos());
  await browser.close(); srv.kill(); web.close(); process.exit(0);
})();
